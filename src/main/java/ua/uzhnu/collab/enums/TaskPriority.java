package ua.uzhnu.collab.enums;

/**
 * Пріоритет задачі — визначає важливість і терміновість виконання.
 *
 * <p>У канбан-дошці відображається у вигляді кольорової позначки:
 * LOW (сірий), MEDIUM (синій), HIGH (помаранчевий), CRITICAL (червоний).
 */
public enum TaskPriority {

  /** Низький пріоритет — виконати при нагоді. */
  LOW,

  /** Середній пріоритет — стандартне завдання. */
  MEDIUM,

  /** Високий пріоритет — потребує уваги найближчим часом. */
  HIGH,

  /** Критичний пріоритет — негайне виконання. */
  CRITICAL
}
