package ua.uzhnu.collab.enums;

/**
 * Роль учасника в команді — визначає рівень доступу до операцій.
 *
 * <p>Ієрархія прав: {@code MEMBER < ADMIN < OWNER}.
 * <ul>
 *   <li>{@code MEMBER} — читання та коментування задач, надсилання повідомлень, завантаження файлів.
 *   <li>{@code ADMIN} — все вище + додавання/видалення учасників, редагування задач.
 *   <li>{@code OWNER} — повний контроль, включаючи зміну ролей та видалення команди.
 * </ul>
 *
 * <p>У кожній команді є щонайменше один {@code OWNER}.
 * Роль {@code OWNER} не можна призначити через {@code addMember} — лише через {@code changeRole}.
 */
public enum TeamRole {

  /** Власник команди. Повний доступ, неможливо видалити якщо єдиний. */
  OWNER,

  /** Адміністратор. Може керувати учасниками та задачами. */
  ADMIN,

  /** Звичайний учасник. Може працювати із задачами та файлами. */
  MEMBER
}
